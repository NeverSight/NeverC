int main(void) {
    neverc_x509_cert_t root;
    neverc_x509_cert_t leaf;
    int root_ok =
        neverc_x509_parse_certificate(&root, root_der, sizeof(root_der)) == 0;
    int leaf_ok =
        neverc_x509_parse_certificate(&leaf, leaf_der, sizeof(leaf_der)) == 0;
    CHECK("parse_root", root_ok);
    CHECK("parse_leaf", leaf_ok);
    if (!root_ok || !leaf_ok) {
        if (root_ok)
            neverc_x509_cert_free(&root);
        if (leaf_ok)
            neverc_x509_cert_free(&leaf);
        return 1;
    }

    const neverc_x509_cert_t *chain[] = {&leaf, &root};
    neverc_x509_time_t valid_time = {2024, 1, 1, 0, 0, 0};
    CHECK("valid_server_chain",
          neverc_x509_verify_chain(
              chain, 2, &valid_time, "example",
              NEVERC_X509_EXT_KEY_USAGE_SERVER_AUTH) == 0);
    CHECK("hostname_mismatch_rejected",
          neverc_x509_verify_chain(
              chain, 2, &valid_time, "other.example",
              NEVERC_X509_EXT_KEY_USAGE_SERVER_AUTH) != 0);
    CHECK("wrong_eku_rejected",
          neverc_x509_verify_chain(
              chain, 2, &valid_time, "example",
              NEVERC_X509_EXT_KEY_USAGE_CODE_SIGNING) != 0);

    neverc_x509_cert_t non_self_signed_anchor = root;
    non_self_signed_anchor.raw_issuer = leaf.raw_subject;
    non_self_signed_anchor.raw_issuer_len = leaf.raw_subject_len;
    const neverc_x509_cert_t *explicit_anchor_chain[] = {
        &leaf, &non_self_signed_anchor
    };
    CHECK("explicit_trust_anchor_need_not_be_self_signed",
          neverc_x509_verify_chain(
              explicit_anchor_chain, 2, &valid_time, "example",
              NEVERC_X509_EXT_KEY_USAGE_SERVER_AUTH) == 0);

    neverc_x509_cert_t v1_intermediate = root;
    v1_intermediate.version = 0;
    v1_intermediate.basic_constraints_valid = 0;
    v1_intermediate.is_ca = 0;
    v1_intermediate.max_path_len = -1;
    const neverc_x509_cert_t *v1_intermediate_chain[] = {
        &leaf, &v1_intermediate, &root
    };
    CHECK("v1_intermediate_rejected",
          neverc_x509_verify_chain(
              v1_intermediate_chain, 3, &valid_time, "example",
              NEVERC_X509_EXT_KEY_USAGE_SERVER_AUTH) != 0);

    neverc_x509_cert_t non_self_issued_intermediate = root;
    non_self_issued_intermediate.raw_issuer = leaf.raw_subject;
    non_self_issued_intermediate.raw_issuer_len = leaf.raw_subject_len;
    neverc_x509_cert_t constrained_anchor = root;
    constrained_anchor.raw_subject = leaf.raw_subject;
    constrained_anchor.raw_subject_len = leaf.raw_subject_len;
    constrained_anchor.max_path_len = 0;
    const neverc_x509_cert_t *constrained_chain[] = {
        &leaf, &non_self_issued_intermediate, &constrained_anchor
    };
    CHECK("path_length_constraint_rejected",
          neverc_x509_verify_chain(
              constrained_chain, 3, &valid_time, "example",
              NEVERC_X509_EXT_KEY_USAGE_SERVER_AUTH) != 0);
    constrained_anchor.max_path_len = 1;
    CHECK("path_length_constraint_allows_one_ca",
          neverc_x509_verify_chain(
              constrained_chain, 3, &valid_time, "example",
              NEVERC_X509_EXT_KEY_USAGE_SERVER_AUTH) == 0);

    neverc_x509_time_t expired_time = {2030, 1, 1, 0, 0, 0};
    CHECK("expired_chain_rejected",
          neverc_x509_verify_chain(
              chain, 2, &expired_time, "example",
              NEVERC_X509_EXT_KEY_USAGE_SERVER_AUTH) != 0);

    const neverc_x509_cert_t *reversed_chain[] = {&root, &leaf};
    CHECK("reversed_chain_rejected",
          neverc_x509_verify_chain(
              reversed_chain, 2, &valid_time, NULL,
              NEVERC_X509_EXT_KEY_USAGE_SERVER_AUTH) != 0);

    uint8_t tampered_der[sizeof(leaf_der)];
    memcpy(tampered_der, leaf_der, sizeof(tampered_der));
    tampered_der[sizeof(tampered_der) - 1] ^= 1;
    neverc_x509_cert_t tampered_leaf;
    int tampered_ok = neverc_x509_parse_certificate(
        &tampered_leaf, tampered_der, sizeof(tampered_der)) == 0;
    CHECK("parse_tampered_leaf", tampered_ok);
    if (tampered_ok) {
        const neverc_x509_cert_t *tampered_chain[] = {
            &tampered_leaf, &root
        };
        CHECK("tampered_signature_rejected",
              neverc_x509_verify_chain(
                  tampered_chain, 2, &valid_time, "example",
                  NEVERC_X509_EXT_KEY_USAGE_SERVER_AUTH) != 0);
        neverc_x509_cert_free(&tampered_leaf);
    }

    neverc_x509_cert_free(&leaf);
    neverc_x509_cert_free(&root);
    printf("%d tests, %d failed\n", tests_run, tests_failed);
    if (tests_failed == 0)
        puts("passed");
    return tests_failed != 0;
}
