size_t neverc_hex_decoded_len(size_t n) {
    return n / 2;
}

int neverc_hex_decode(uint8_t *dst, const char *src, size_t src_len) {
    if (src_len % 2 != 0)
        return -1;

    size_t out = 0;
    for (size_t j = 0; j < src_len; j += 2) {
        uint8_t a = reverse_hex[(uint8_t)src[j]];
        uint8_t b = reverse_hex[(uint8_t)src[j + 1]];
        if (a > 0x0f || b > 0x0f)
            return -1;
        dst[out++] = (a << 4) | b;
    }
    return (int)out;
}
