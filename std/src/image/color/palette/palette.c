static int color_dist_sq(int r1, int g1, int b1, int r2, int g2, int b2) {
    int dr = r1 - r2, dg = g1 - g2, db = b1 - b2;
    return dr*dr + dg*dg + db*db;
}

int neverc_palette_plan9_index(uint8_t r, uint8_t g, uint8_t b) {
    int best = 0, best_dist = color_dist_sq(r, g, b,
        neverc_palette_plan9[0].r, neverc_palette_plan9[0].g, neverc_palette_plan9[0].b);
    for (int i = 1; i < NEVERC_PALETTE_PLAN9_LEN; i++) {
        int d = color_dist_sq(r, g, b,
            neverc_palette_plan9[i].r, neverc_palette_plan9[i].g, neverc_palette_plan9[i].b);
        if (d < best_dist) { best_dist = d; best = i; }
    }
    return best;
}

